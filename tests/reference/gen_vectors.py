"""Generate the golden vectors used by every implementation's tests.

Outputs (all checked in):

* ``vectors/golden.json``      - language-neutral source of truth
* ``vectors/golden.mjs``       - ES module for the PWA / hybrid JS code
* ``vectors/GoldenVectors.kt`` - Kotlin object for the Android JVM tests

Run: ``python tests/reference/gen_vectors.py``
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TESTS = HERE.parent
sys.path.insert(0, str(HERE))

import protocol_ref as ref  # noqa: E402

PIN = 123789
VECTORS_DIR = TESTS / "vectors"


def _encode_vectors() -> list[dict]:
    out = []
    for action, (press, release) in ref.COMMANDS.items():
        for label, cmd_hex in (("press", press), ("release", release)):
            if not cmd_hex:
                continue
            out.append({
                "id": f"encode.{action}.{label}",
                "kind": "encode",
                "pin": PIN,
                "cmd": cmd_hex,
                "expect": ref.encode_command(bytes.fromhex(cmd_hex), PIN).hex().upper(),
            })
    # other PINs must derive different keys (guards against hard-coded keys)
    for pin in (0, 1, 999999):
        for action in ("lock", "start"):
            cmd = ref.COMMANDS[action][0]
            out.append({
                "id": f"encode.{action}.pin{pin}",
                "kind": "encode",
                "pin": pin,
                "cmd": cmd,
                "expect": ref.encode_command(bytes.fromhex(cmd), pin).hex().upper(),
            })
    return out


def _decode_vectors() -> list[dict]:
    """Encrypt known plaintexts with the device key, then require decoders to
    recover the same fields (the plaintexts are real captures)."""
    cases = [
        ("status.locked", "A60802010102010203051100", {"lock": 2, "mode": 1, "pke": 2, "pass1": 3, "pass2": 4}),
        ("status.unlocked", "A60801010102010203051000", {"lock": 1, "mode": 1, "pke": 2, "pass1": 3, "pass2": 4}),
        ("status.started", "A60801020102010203051100", {"lock": 1, "mode": 2, "pke": 2, "pass1": 3, "pass2": 4}),
        ("event.start", "A5010601B6C3FF1F01000000A5010606", {"cmd": 6, "lock": 1}),
        ("event.unlock", "A5010101B6C3FF1FA501010100000000", {"cmd": 1, "lock": 1}),
        ("heartbeat", "A9014B4B4BB3FF1FA9014B4B4BB3FF1F", {"counter": 0x4B}),
    ]
    out = []
    dev_key = ref.derive_key(b"Lenzedev", PIN)
    for name, plain_hex, fields in cases:
        plain = bytes.fromhex(plain_hex)
        if len(plain) < 16:
            plain = plain + bytes(16 - len(plain))
        cipher = ref.aes128_encrypt_block(plain[:16], dev_key)
        item = {
            "id": f"decode.{name}",
            "kind": "decode",
            "pin": PIN,
            "cipher": cipher.hex().upper(),
            "plain": plain_hex,
        }
        item.update({k: v for k, v in fields.items()})
        item["expect"] = fields
        out.append(item)
    # wrong PIN must not decode to the same fields
    out.append({
        "id": "decode.wrongPin",
        "kind": "decode",
        "pin": 111111,
        "cipher": ref.aes128_encrypt_block(
            bytes.fromhex("A60802010102010203051100") + bytes(4),
            ref.derive_key(b"Lenzedev", PIN),
        ).hex().upper(),
        "expect_kind_not": "status",
    })
    return out


def _checksum_vectors() -> list[dict]:
    out = []
    cases = [
        ("A600", 0x00),
        ("A50106", 0x06),
        ("A5010202", (0x02 + 0x02) & 0xFF),
        ("A5015A5A05", (0x5A + 0x5A + 0x05) & 0xFF),
    ]
    for cmd_hex, expect in cases:
        out.append({
            "id": f"checksum.{cmd_hex}",
            "kind": "checksum",
            "cmd": cmd_hex,
            "expect": expect & 0xFF,
        })
    return out


def main() -> None:
    ref.self_check()
    vectors = {
        "meta": {"pin": PIN, "generated_by": "tests/reference/gen_vectors.py"},
        "vectors": _encode_vectors() + _decode_vectors() + _checksum_vectors(),
    }

    VECTORS_DIR.mkdir(parents=True, exist_ok=True)
    (VECTORS_DIR / "golden.json").write_text(
        json.dumps(vectors, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    # JS binding: kept intentionally simple so it can be imported directly.
    js = "// generated by tests/reference/gen_vectors.py - do not edit\n"
    js += "export const golden = " + json.dumps(vectors, ensure_ascii=False, indent=2) + ";\n"
    js += "export default golden;\n"
    (VECTORS_DIR / "golden.mjs").write_text(js, encoding="utf-8")

    # Kotlin binding for the Android JVM tests.
    kt = ["// generated by tests/reference/gen_vectors.py - do not edit",
          "object GoldenVectors {"]
    kt.append("    const val PIN = %d" % PIN)
    kt.append("    val encode: Map<String, Pair<String, String>> = mapOf(")
    for v in _encode_vectors():
        kt.append('        "%s" to ("%s" to "%s"),' % (v["id"], v["cmd"], v["expect"]))
    kt.append("    )")
    kt.append("    val decode: Map<String, Pair<String, String>> = mapOf(")
    for v in _decode_vectors():
        kt.append('        "%s" to ("%s" to "%s"),' % (v["id"], v["cipher"], v.get("plain", "")))
    kt.append("    )")
    kt.append("}")
    (VECTORS_DIR / "GoldenVectors.kt").write_text("\n".join(kt) + "\n", encoding="utf-8")

    print("wrote %d vectors -> %s" % (len(vectors["vectors"]), VECTORS_DIR))


if __name__ == "__main__":
    main()
